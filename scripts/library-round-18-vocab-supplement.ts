export type Supplement = { word: string; definition: string };
export const vocabSupplement: Record<string, Supplement[]> = {};
for (const line of rows) {
  const [title, ...entries] = line.trim().split('|');
  if (entries.length !== 2 || vocabSupplement[title]) throw new Error(`Bad supplement row: ${line}`);
  vocabSupplement[title] = entries.map((entry) => {
    const [word, definition] = entry.split('~');
    if (!word || !definition) throw new Error(`Bad supplement term: ${entry}`);
    return { word, definition };
  });
}
