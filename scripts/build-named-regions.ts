/** Run locally: npx tsx scripts/build-named-regions.ts [--cache <directory>] */
import { writeFile } from 'node:fs/promises';
import { features, polygons, SOURCES, type XY } from './terrain-data-utils';
import { polygonArea, unwrapRing } from '../src/lib/live-room/terrain-geometry';
import { TEACHING_LANDMARKS } from './terrain-landmarks';

/** Iterative Douglas-Peucker on an open line; tolerance is in degrees. */
function simplifyLine(points: XY[], tolerance: number): XY[] {
  if (points.length <= 2) return points;
  const keep: Record<number, boolean> = { 0: true, [points.length - 1]: true };
  const stack = [[0, points.length - 1]];
  while (stack.length) {
    const [start, end] = stack.pop()!;
    const [ax, ay] = points[start], [bx, by] = points[end];
    const dx = bx - ax, dy = by - ay, length = dx * dx + dy * dy;
    let max = tolerance * tolerance, selected = -1;
    for (let i = start + 1; i < end; i++) {
      const [x, y] = points[i];
      const t = length ? Math.max(0, Math.min(1, ((x - ax) * dx + (y - ay) * dy) / length)) : 0;
      const distance = (x - ax - t * dx) ** 2 + (y - ay - t * dy) ** 2;
      if (distance > max) { selected = i; max = distance; }
    }
    if (selected >= 0) { keep[selected] = true; stack.push([start, selected], [selected, end]); }
  }
  return points.filter((_, i) => keep[i]);
}

export function simplifyRing(ring: XY[], tolerance: number): XY[] {
  const unwrapped = unwrapRing(ring);
  let farthest = 1, distance = 0;
  for (let i = 1; i < unwrapped.length - 1; i++) {
    const d = (unwrapped[i][0] - unwrapped[0][0]) ** 2 + (unwrapped[i][1] - unwrapped[0][1]) ** 2;
    if (d > distance) { distance = d; farthest = i; }
  }
  let simple = simplifyLine(unwrapped.slice(0, farthest + 1), tolerance).slice(0, -1)
    .concat(simplifyLine(unwrapped.slice(farthest), tolerance));
  // Keep a triangle for tiny islands/holes rather than restoring hundreds of vertices.
  if (simple.length < 4) {
    let third = 1, maxArea = -1;
    const [ax, ay] = unwrapped[0], [bx, by] = unwrapped[farthest];
    for (let i = 1; i < unwrapped.length - 1; i++) {
      const area = Math.abs((bx - ax) * (unwrapped[i][1] - ay) - (by - ay) * (unwrapped[i][0] - ax));
      if (area > maxArea) { maxArea = area; third = i; }
    }
    simple = [unwrapped[0], ...[farthest, third].sort((a, b) => a - b).map(i => unwrapped[i]), unwrapped[unwrapped.length - 1]];
  }
  return simple.map(([x, y]) => [Math.round(x * 1000) / 1000, Math.round(y * 1000) / 1000]);
}

const KINDS: Record<string, string> = {
  'Range/mtn': 'mountain-range', Desert: 'desert', Plain: 'plain', Plateau: 'plateau',
  Delta: 'delta', Island: 'island', 'Island group': 'island', Wetlands: 'wetlands',
  Gorge: 'canyon', Tundra: 'tundra', Basin: 'basin', Valley: 'valley',
};

export async function buildNamedRegions(): Promise<void> {
  const land = await features(SOURCES.regions), marine = await features(SOURCES.marine);
  const records = [];
  for (const feature of land.concat(marine)) {
    const p = feature.properties;
    const category = String(p.FEATURECLA || p.featurecla);
    const isMarine = p.featurecla !== undefined;
    // Marine layer supplies named reefs; broad sea/ocean labels are outside this brief.
    if (isMarine && category !== 'reef') continue;
    const kind = isMarine ? category : KINDS[category];
    if (!kind || (kind === 'island' && Number(p.SCALERANK) > 4)) continue;
    const name = String(p.NAME_EN || p.name_en || p.NAME || p.name);
    const shapes = polygons(feature).map(polygon => polygon.map(ring => simplifyRing(ring, 0.12)));
    const geometry = shapes.map(polygon => polygon.map(ring => {
      let x = 0, y = 0;
      return ring.map(([lng, lat]) => {
        const nextX = Math.round(lng * 1000), nextY = Math.round(lat * 1000);
        const pair = (nextX - x).toString(36) + '.' + (nextY - y).toString(36);
        x = nextX; y = nextY;
        return pair;
      }).join('.');
    }).join('~')).join('|');
    // Area before simplification avoids changing overlap priority with tolerance.
    const areaKm2 = Math.round(polygons(feature).reduce((sum, p) => sum + polygonArea(p), 0));
    records.push({ name, kind, areaKm2, geometry });
  }
  records.sort((a, b) => a.areaKm2 - b.areaKm2 || a.name.localeCompare(b.name));
  const output = `/** Generated by scripts/build-named-regions.ts. DO NOT EDIT.
 * Natural Earth v5.1.2, 1:10m geography regions + marine polygons; public domain.
 * Made with Natural Earth. naturalearthdata.com. Simplified at 0.12 degrees.
 * Editorial teaching landmarks and original facts: CC0; radii are approximate.
 * Sources, limitations and reproduction: docs/terrain-data-sources.md.
 */
export interface NamedRegion {
  name: string; kind: string; areaKm2: number; geometry: string;
}
/** Geometry: polygons separated by |, rings by ~, base36 integer delta pairs by .;
 * coordinates are quantised to 0.001 degrees and decoded once by the lookup. */
export interface TeachingLandmark {
  name: string; kind: 'volcano' | 'canyon'; lat: number; lng: number;
  radiusKm: number; fact: string; source: string;
}
export const NAMED_REGIONS: NamedRegion[] = [
${records.map(r => JSON.stringify(r)).join(',\n')}
];
export const TEACHING_LANDMARKS: TeachingLandmark[] = ${JSON.stringify(TEACHING_LANDMARKS, null, 2)};
`;
  if (Buffer.byteLength(output) >= 200000) throw new Error('Named regions exceed 200 KB: ' + Buffer.byteLength(output));
  await writeFile('src/data/world/named-regions.ts', output);
  console.log(JSON.stringify({ bytes: Buffer.byteLength(output), regions: records.length, landmarks: TEACHING_LANDMARKS.length }, null, 2));
}

if (require.main === module) buildNamedRegions().catch(error => { console.error(error); process.exitCode = 1; });
