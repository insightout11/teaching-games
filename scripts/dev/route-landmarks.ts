/**
 * Which landmarks the class can really see, on which routes. Every pair of the app's destination cities, the cruise
 * part of the flight only (take-off and landing are their own moments), with the cockpit's own view rule
 * (src/lib/live-room/landmarks-ahead.ts). Writes docs/route-landmarks.md. Re-run when cities or landmarks change:
 *   npx tsx --tsconfig tsconfig.json scripts/dev/route-landmarks.ts
 */
import { writeFileSync } from 'fs';
import { WORLD_DESTINATIONS } from '@/data/world-flight/destinations';
import { LANDMARK_CATALOG } from '@/data/world/landmark-catalog';
import { greatCirclePoint } from '@/lib/live-room/route-terrain';
import { bearingDeg } from '@/lib/live-room/sun';
import { catalogueInView } from '@/lib/live-room/landmarks-ahead';

const DRAWN = new Set(['fuji', 'pyramids', 'everest', 'matterhorn', 'kilimanjaro', 'niagara', 'volcano']);
const cities = WORLD_DESTINATIONS.map((d) => ({ city: d.city, lat: d.lat, lng: d.lng }));
const routes: Record<string, string[]> = {};
let pairs = 0;
for (const a of cities) for (const b of cities) {
  if (a.city >= b.city) continue;
  pairs++;
  const seen = new Set<string>();
  // the cruise: from 2% to 98% of the way (the descent is the last few minutes; landmarks stay out of it)
  for (let i = 4; i <= 196; i++) {
    const t = i / 200, p = greatCirclePoint(a, b, t), h = bearingDeg(p, greatCirclePoint(a, b, Math.min(1, t + 0.005)));
    for (const l of catalogueInView(p, h)) seen.add(l.id);
  }
  seen.forEach((id) => { (routes[id] ??= []).push(`${a.city} – ${b.city}`); });
}
const rows = LANDMARK_CATALOG.map((l) => ({ l, r: routes[l.id] ?? [] })).sort((x, y) => y.r.length - x.r.length);
const line = (x: (typeof rows)[number]) => `| ${x.l.name} | ${x.l.shape}${DRAWN.has(x.l.shape) ? ' (drawn)' : ''} | ${x.r.length} | ${x.r.slice(0, 5).join('; ')}${x.r.length > 5 ? '; …' : ''} |`;
const md = `# Landmarks on real routes

Generated by \`scripts/dev/route-landmarks.ts\` from the app's ${cities.length} destination cities (${pairs} city pairs, both
directions count once), the cruise part of each flight, and the cockpit's view rule (up to about 145 km ahead, sideways
out to about half the distance ahead). Re-run it when cities or landmarks change.

**Seen on at least one route: ${rows.filter((x) => x.r.length).length} of ${rows.length} landmarks.** Never seen:
${rows.filter((x) => !x.r.length).map((x) => x.l.name).join(', ') || 'none'}.

| Landmark | Shape | Routes | Some routes |
|---|---|---|---|
${rows.map(line).join('\n')}
`;
writeFileSync('docs/route-landmarks.md', md);
