/** Run locally: npx tsx scripts/build-land-cover.ts [--cache <directory>] */
import { mkdir, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import path from 'node:path';
import { features, MODIS_URL, polygons, readPng, source, SOURCES } from './terrain-data-utils';
import { inPolygon } from '../src/lib/live-room/terrain-geometry';

export const LEGEND = {
  A: 'ocean', B: 'ice', C: 'tundra', D: 'boreal-forest', E: 'forest',
  F: 'rainforest', G: 'savanna', H: 'grassland', I: 'farmland', J: 'rice-paddies',
  K: 'desert', L: 'salt-flats', M: 'wetlands', N: 'mountains', O: 'city',
} as const;
type Code = keyof typeof LEGEND;

/** Explicit source-to-scene approximation; see docs/terrain-data-sources.md. */
export function classify(igbp: number, lat: number): Code {
  switch (igbp) {
    case 0: case 17: return 'A';
    case 1: case 3: return lat >= 45 ? 'D' : 'E';
    case 2: return Math.abs(lat) <= 25 ? 'F' : 'E';
    case 4: case 5: return 'E';
    case 6: case 7: case 10: return lat >= 60 ? 'C' : 'H';
    case 8: return lat >= 45 ? 'D' : 'G';
    case 9: return lat >= 60 ? 'C' : Math.abs(lat) <= 35 ? 'G' : 'H';
    case 11: return 'M';
    case 12: case 14: return 'I';
    case 13: return 'O';
    case 15: return 'B';
    case 16: return 'K';
    default: throw new Error('Unclassified IGBP value: ' + igbp);
  }
}

export function encodeRuns(grid: string): string {
  return grid.replace(/([A-O])\1*/g, run => run.length.toString(36) + run[0]);
}

export async function buildLandCover(): Promise<void> {
  const png = await source({ file: 'modis-2024.png', url: MODIS_URL, sha256: 'b018596ab88ead500604e403202896a3083f3e8833c13a64667b18a347a81d08' });
  const image = readPng(png);
  if (image.width !== 720 || image.height !== 360) throw new Error('Expected 720 x 360');
  const xml = (await source(SOURCES.legend)).toString('utf8');
  const colours: Record<string, number> = {};
  const pattern = /<ColorMapEntry rgb="([0-9,]+)"[^>]*sourceValue="([0-9,]+)"/g;
  let match: RegExpExecArray | null;
  while ((match = pattern.exec(xml))) colours[match[1]] = Number(match[2].split(',')[0]);
  if (Object.keys(colours).length !== 18) throw new Error('Unexpected MODIS legend');
  const regions = await features(SOURCES.regions);
  const refinements = regions.filter(f => f.properties.FEATURECLA === 'Range/mtn' || /^(Salar|Salina|Salt)\b/i.test(String(f.properties.NAME)));
  // Precompute bounding boxes: only do polygon work for plausible candidates.
  const shapes = refinements.map(f => ({
    salt: f.properties.FEATURECLA !== 'Range/mtn',
    shapes: polygons(f).map(polygon => {
      const ring = polygon[0];
      return { polygon, minX: Math.min(...ring.map(p => p[0])), maxX: Math.max(...ring.map(p => p[0])), minY: Math.min(...ring.map(p => p[1])), maxY: Math.max(...ring.map(p => p[1])) };
    }),
  }));
  const rows: string[] = [];
  const counts: Record<string, number> = {};
  for (let y = 0; y < 360; y++) {
    const lat = 90 - (y + 0.5) * 0.5;
    let row = '';
    for (let x = 0; x < 720; x++) {
      const lng = -180 + (x + 0.5) * 0.5, i = (y * 720 + x) * 4;
      let code: Code;
      if (image.rgba[i + 3] === 0) code = lat < -60 ? 'B' : 'A';
      else {
        if (image.rgba[i + 3] !== 255) throw new Error('Antialiased category');
        const rgb = Array.from(image.rgba.subarray(i, i + 3)).join(',');
        if (!(rgb in colours)) throw new Error('Unknown categorical colour: ' + rgb);
        let igbp = colours[rgb];
        // GIBS has 98 unclassified pixels along its western image seam.
        // Fill only that seam from the adjacent observed cell, never inland gaps.
        if (igbp === 255 && x === 0) {
          const adjacent = Array.from(image.rgba.subarray(i + 4, i + 7)).join(',');
          igbp = colours[adjacent];
        }
        code = classify(igbp, lat);
      }
      if ('DEFGHCK'.includes(code)) {
        // Salt refinement wins over an overlapping range, but only on barren land.
        const matches = shapes.filter(s => s.shapes.some(p => lng >= p.minX && lng <= p.maxX && lat >= p.minY && lat <= p.maxY && inPolygon(lng, lat, p.polygon)));
        if (code === 'K' && matches.some(s => s.salt)) code = 'L';
        else if (matches.some(s => !s.salt)) code = 'N';
      }
      row += code;
      counts[LEGEND[code]] = (counts[LEGEND[code]] || 0) + 1;
    }
    rows.push(encodeRuns(row));
  }
  const payload = rows.join('');
  const output = `/** Generated by scripts/build-land-cover.ts. DO NOT EDIT.
 * NASA MODIS MCD12Q1 V061 (2024), NASA EOSDIS GIBS; CC0.
 * Mountain/salt refinements: Natural Earth v5.1.2, public domain.
 * 0.5-degree cell centres, N to S and W to E. Water includes lakes.
 * Source PNG SHA-256: ${createHash('sha256').update(png).digest('hex')}
 * Limitations and attribution: docs/terrain-data-sources.md.
 */
export const LAND_COVER_RESOLUTION = 0.5;
export const LAND_COVER_WIDTH = 720;
export const LAND_COVER_HEIGHT = 360;
export const LAND_COVER_LEGEND = ${JSON.stringify(LEGEND, null, 2)} as const;
export type LandCover = typeof LAND_COVER_LEGEND[keyof typeof LAND_COVER_LEGEND];
/** Base-36 run length followed by an uppercase legend code. */
export const LAND_COVER_RUNS = [
${rows.map(row => '  ' + JSON.stringify(row)).join(',\n')}
].join('');
`;
  if (Buffer.byteLength(output) >= 300000) throw new Error('Land cover exceeds 300 KB');
  const target = path.resolve('src/data/world/land-cover.ts');
  await mkdir(path.dirname(target), { recursive: true });
  await writeFile(target, output);
  console.log(JSON.stringify({ bytes: Buffer.byteLength(output), runs: payload.length, cells: 720 * 360, counts }, null, 2));
}

if (require.main === module) buildLandCover().catch(error => { console.error(error); process.exitCode = 1; });
